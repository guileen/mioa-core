// HTML named character references for Zig consumers. The Rust HTML tokenizer
// retains its own internal html5ever table; this module replaces only the
// named-character-reference FFI used by cue text parsing.
const std = @import("std");
const data = @import("entities_data.zig");

/// Looks up a name without its leading '&', matching html5ever's contract:
/// 0 = no entity starts with name, 1 = prefix only, 2 = exact match.
/// Only an exact match writes out; out[1] is zero for a single scalar.
/// Legacy semicolonless names are exact matches, even when longer names exist.
/// Empty input is a prefix. Names are case-sensitive ASCII, so non-ASCII
/// input (including invalid UTF-8) cannot match an entity or its prefix.
/// No allocation, initialization, or UTF-8 decoding is needed. Input length
/// is bounded before comparison, and at most 12 binary-search steps are used.
pub fn lookup(name: []const u8, out: *[2]u32) u8 {
    if (name.len > data.max_name_length) return 0;

    // Find the first name >= the input. If any entity starts with the input,
    // this is the first such entity; no separate materialized prefix table
    // is necessary.
    var low: usize = 0;
    var high: usize = data.entries.len;
    while (low < high) {
        const mid = low + (high - low) / 2;
        switch (std.mem.order(u8, data.entries[mid].name, name)) {
            .lt => low = mid + 1,
            .eq, .gt => high = mid,
        }
    }
    if (low == data.entries.len) return 0;
    const entry = data.entries[low];
    if (std.mem.eql(u8, entry.name, name)) {
        out.* = entry.codepoints;
        return 2;
    }
    return if (std.mem.startsWith(u8, entry.name, name)) 1 else 0;
}

const testing = std.testing;

fn expectLookup(name: []const u8, expected: [2]u32) !void {
    var out: [2]u32 = .{ 0xDEADBEEF, 0xCAFEBABE };
    try testing.expectEqual(@as(u8, 2), lookup(name, &out));
    try testing.expectEqual(expected, out);
}

fn expectUnchanged(name: []const u8, expected: u8) !void {
    const sentinel: [2]u32 = .{ 0xDEADBEEF, 0xCAFEBABE };
    var out = sentinel;
    try testing.expectEqual(expected, lookup(name, &out));
    try testing.expectEqual(sentinel, out);
}

test "entities: prefixes, exact matches, and dead ends preserve output" {
    try expectUnchanged("", 1);
    try expectUnchanged("a", 1);
    try expectUnchanged("am", 1);
    try expectLookup("amp", .{ '&', 0 });
    try expectLookup("amp;", .{ '&', 0 });
    try expectUnchanged("ampx", 0);
    try expectUnchanged("amp;;", 0);
    try expectUnchanged("&amp;", 0);
    try expectUnchanged("zzzz;", 0);
}

test "entities: longest ambiguity retains the shorter exact name" {
    try expectUnchanged("no", 1);
    try expectLookup("not", .{ 0x00AC, 0 });
    try expectUnchanged("noti", 1);
    try expectUnchanged("notin", 1);
    try expectLookup("notin;", .{ 0x2209, 0 });
    try expectUnchanged("notit", 0);
    try expectUnchanged("notinX", 0);
}

test "entities: case and legacy semicolon aliases" {
    try expectLookup("AMP", .{ '&', 0 });
    try expectLookup("AMP;", .{ '&', 0 });
    try expectUnchanged("Amp;", 0);
    try expectLookup("Aacute", .{ 0x00C1, 0 });
    try expectLookup("Aacute;", .{ 0x00C1, 0 });
    try expectLookup("aacute;", .{ 0x00E1, 0 });
    try expectUnchanged("apos", 1);
    try expectLookup("apos;", .{ '\'', 0 });
}

test "entities: two scalars, astral characters, and longest name" {
    // Concrete Unicode values from the HTML named character references table,
    // not expected values generated by walking the implementation data.
    try expectLookup("NotEqualTilde;", .{ 0x2242, 0x0338 });
    try expectLookup("fjlig;", .{ 'f', 'j' });
    try expectLookup("Afr;", .{ 0x1D504, 0 });
    try expectLookup("Tab;", .{ 0x0009, 0 });
    try expectLookup("NewLine;", .{ 0x000A, 0 });
    try expectUnchanged("CounterClockwiseContourIntegral", 1);
    try expectLookup("CounterClockwiseContourIntegral;", .{ 0x2233, 0 });
    try expectUnchanged("CounterClockwiseContourIntegralX;", 0);
    try expectUnchanged("CounterClockwiseContourIntegral;;", 0);
    try expectUnchanged("aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa", 0);
}

test "entities: invalid UTF-8 and non-ASCII never match or modify output" {
    try expectUnchanged("\xFF", 0);
    try expectUnchanged("a\x80", 0);
    try expectUnchanged("am\xC0\xAF", 0);
    try expectUnchanged("amp;\xFF", 0);
    try expectUnchanged("\xF0\x9F\x92", 0);
    try expectUnchanged("\xED\xA0\x80", 0);
    try expectUnchanged("\xF4\x90\x80\x80", 0);
    try expectUnchanged("\x00", 0);
    try expectUnchanged("a\x00", 0);
    try expectUnchanged("é", 0);
    try expectUnchanged("𝔄", 0);
}
